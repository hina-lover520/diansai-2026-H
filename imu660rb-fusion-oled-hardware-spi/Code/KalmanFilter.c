// /*===========================================================================
//  * 卡尔曼滤波 — 实现文件
//  *===========================================================================
//  *
//  * 【卡尔曼滤波的"模型"详解】
//  *
//  * 每个卡尔曼滤波器都建立在两个核心数学模型之上：
//  *
//  * ┌──────────────────────────────────────────────────────────────┐
//  * │ 模型一：状态转移模型（Process Model / Motion Model）          │
//  * │                                                              │
//  * │   x(k) = F * x(k-1) + B * u(k) + w                          │
//  * │                                                              │
//  * │   描述了系统在没有外部测量的情况下，自身如何随时间演化。       │
//  * │   这是你的"物理直觉"写成数学公式。                            │
//  * │                                                              │
//  * │   举例（角度估计）：                                          │
//  * │     角度(k) = 角度(k-1) + 角速度(k-1) * dt                  │
//  * │     角速度(k) = 角速度(k-1)                                   │
//  * │                                                              │
//  * │     写成矩阵：F = [1, dt; 0, 1]  ← 这就是模型！             │
//  * │                                                              │
//  * │   w ~ N(0, Q) 是过程噪声：承认模型不是完美的                  │
//  * │   Q 越大 = "我不太信我的模型" → 滤波器更相信传感器            │
//  * │   Q 越小 = "模型很准" → 滤波器更相信预测值                    │
//  * └──────────────────────────────────────────────────────────────┘
//  *
//  * ┌──────────────────────────────────────────────────────────────┐
//  * │ 模型二：观测模型（Measurement Model / Observation Model）     │
//  * │                                                              │
//  * │   z(k) = H * x(k) + v                                       │
//  * │                                                              │
//  * │   描述了传感器测量值和真实状态之间的关系。                     │
//  * │                                                              │
//  * │   举例（IMU 测角度）：                                        │
//  * │     z(角度) = 1.0 * 真实角度 + 噪声                          │
//  * │                                                              │
//  * │     写成矩阵：H = [1, 0]  ← 这就是观测模型！                 │
//  * │     意思是：测量值(角度) = 1×状态(角度) + 0×状态(角速度)      │
//  * │                                                              │
//  * │   v ~ N(0, R) 是测量噪声：承认传感器不是完美的                │
//  * │   R 越大 = "传感器很吵" → 滤波器更相信模型预测                │
//  * │   R 越小 = "传感器很准" → 滤波器更相信测量值                  │
//  * └──────────────────────────────────────────────────────────────┘
//  *
//  * ┌──────────────────────────────────────────────────────────────┐
//  * │ 卡尔曼增益 K — 自动权衡                                       │
//  * │                                                              │
//  * │   K = P * H^T / (H * P * H^T + R)                            │
//  * │                                                              │
//  * │   如果 R 很大（传感器不准）→ K 很小 → 信模型多                │
//  * │   如果 P 很大（模型不准）   → K 很大 → 信传感器多              │
//  * │                                                              │
//  * │   关键：K 不是手动调的！它根据 Q 和 R 的比值自动平衡。        │
//  * └──────────────────────────────────────────────────────────────┘
//  *
//  *===========================================================================*/

