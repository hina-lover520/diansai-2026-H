// /*---------------------------------------------------------------------------
//  * 扩展卡尔曼滤波器（EKF）框架
//  *---------------------------------------------------------------------------
//  *
//  * 【什么时候需要 EKF？】
//  * 当你的模型是非线性的：
//  *   - 状态转移用了 sin/cos/tan（如欧拉角动力学）
//  *   - 观测用了 arctan/arcsin（如加速度计求角度 = atan2(ay, az)）
//  *   - 状态是四元数（乘法而非加法）
//  *
//  * 此时标准的 F*x 和 H*x 不适用，需要用 EKF。
//  *
//  * 【EKF 怎么做？】
//  *   预测步：用完整非线性函数 f(x) 推进状态
//  *           用雅可比矩阵 F_jac = ∂f/∂x 推进协方差
//  *   更新步：用非线性函数 h(x) 算预测观测值
//  *           用雅可比矩阵 H_jac = ∂h/∂x 算卡尔曼增益
//  *
//  * 【模型定义 — 你需要提供的三个函数】
//  *
//  * 1. 状态转移函数 f(x, u)
//  *    输入：当前状态 x，控制输入 u
//  *    输出：下一时刻的预测状态
//  *
//  *    例（二维角度+角速度，非线性版）：
//  *    void f_angle(float x[2], float u, float dt, float x_pred[2])
//  *    {
//  *        // 附带简化的非线性项（如角加速度阻尼）
//  *        x_pred[0] = x[0] + x[1]*dt + 0.5f*u*dt*dt;  // 角度
//  *        x_pred[1] = x[1] + u*dt;                     // 角速度
//  *    }
//  *
//  * 2. 状态转移雅可比 F_jac(x, u)
//  *    输入：当前状态 x
//  *    输出：F_jac 矩阵 = ∂f/∂x（f 对每个状态分量的偏导数）
//  *
//  *    例（上面的线性模型 → 雅可比恰好是常数）：
//  *    void F_jacobian_angle(float x[2], float dt, float F[2][2])
//  *    {
//  *        F[0][0] = 1.0f;   F[0][1] = dt;     // ∂f0/∂x0, ∂f0/∂x1
//  *        F[1][0] = 0.0f;   F[1][1] = 1.0f;    // ∂f1/∂x0, ∂f1/∂x1
//  *    }
//  *
//  *    如果是非线性模型（如带 sin 角度耦合的三维姿态）：
//  *    void F_jacobian_attitude(float x[3], float dt, float F[3][3])
//  *    {
//  *        float phi   = x[0];  // roll
//  *        float theta = x[1];  // pitch
//  *        // 欧拉角动力学雅可比（简化版）
//  *        F[0][0] = 1.0f;                              F[0][1] = dt*sin(phi)*tan(theta);  F[0][2] = dt*cos(phi)*tan(theta);
//  *        F[1][0] = 0.0f;                              F[1][1] = 1.0f;                     F[1][2] = -dt*sin(phi);
//  *        F[2][0] = 0.0f;                              F[2][1] = dt*cos(phi)/cos(theta);   F[2][2] = 1.0f;
//  *    }
//  *
//  * 3. 观测函数 h(x) 及其雅可比 H_jac(x)
//  *    输入：状态 x
//  *    输出：预测观测值 + H_jac 矩阵
//  *
//  *    例（加速度计求角度的非线性观测）：
//  *    void h_accel_angle(float x[2], float h_pred[1], float H[1][2])
//  *    {
//  *        // 观测模型：通过加速度比值得角度
//  *        // h(x) = atan2(-ax, az)（但这里 x 已经是角度 → 线性）
//  *        h_pred[0] = x[0];       // 直接观测角度
//  *        H[0][0] = 1.0f;         // ∂h/∂角度 = 1
//  *        H[0][1] = 0.0f;         // ∂h/∂角速度 = 0
//  *    }
//  *
//  *---------------------------------------------------------------------------
//  *
//  * EKF 完整流程伪代码：
//  *
//  * void EKF_Update(float x[], void (*f)(), void (*F_jac)(),
//  *                 void (*h)(), void (*H_jac)(), ...)
//  * {
//  *     // ====== 预测 ======
//  *     // 1. 用非线性 f 推进状态
//  *     f(x, u, dt, x_pred);
//  *
//  *     // 2. 在当前状态处求雅可比
//  *     F_jac(x, u, dt, F);
//  *
//  *     // 3. 协方差预测（和标准 KF 一样，但 F 是雅可比）
//  *     P = F * P * F^T + Q;
//  *
//  *     // ====== 更新 ======
//  *     // 4. 用非线性 h 预测观测值
//  *     h(x_pred, z_pred);
//  *
//  *     // 5. 在预测状态处求观测雅可比
//  *     H_jac(x_pred, H);
//  *
//  *     // 6. 算新息、新息协方差、卡尔曼增益（和标准 KF 一样）
//  *     y = z_measured - z_pred;
//  *     S = H * P * H^T + R;
//  *     K = P * H^T * inv(S);
//  *
//  *     // 7. 状态和协方差更新
//  *     x = x_pred + K * y;
//  *     P = (I - K*H) * P;
//  * }
//  *
//  *---------------------------------------------------------------------------*/

// /*---------------------------------------------------------------------------
//  * 无迹卡尔曼滤波器（UKF）框架
//  *---------------------------------------------------------------------------
//  *
//  * 【什么时候用 UKF 而不是 EKF？】
//  *   - 系统强非线性（如四元数姿态、大角度旋转）
//  *   - EKF 的雅可比推导太复杂或容易出错
//  *   - 需要更高精度（UKF 至少二阶，EKF 一阶）
//  *
//  * 【UKF 的核心思想】
//  *
//  *   EKF 做法：函数 f(x) 在 x 处线性化 → 近似传递一个高斯分布
//  *   UKF 做法：选 2n+1 个"Sigma 点" → 每个点过一遍 f(x)
//  *            → 从变换后的点云重新统计均值和协方差
//  *
//  *   这组 Sigma 点携带了分布的均值和协方差信息，
//  *   穿过非线性函数后仍然能忠实地反映后验分布。
//  *
//  * 【Sigma 点选取（Van der Merwe 方法）】
//  *
//  *   n = 状态维度
//  *   λ = α² * (n + κ) - n
//  *   其中 α = 1e-3 ~ 1（控制点散布距离）
//  *        κ = 3 - n（维度补偿，≥0 保证协方差正定）
//  *
//  *   X₀ = mean                         （中心点）
//  *   Xᵢ = mean + √((n+λ)·P)ᵢ   i=1..n （在协方差主轴方向延伸）
//  *   Xᵢ = mean - √((n+λ)·P)ᵢ₋ₙ i=n+1..2n
//  *
//  *   权重：
//  *     Wm₀ = λ/(n+λ)        （均值权重）
//  *     Wc₀ = λ/(n+λ) + (1-α²+β)  （协方差权重，β 对高斯分布取 2）
//  *     Wmᵢ = Wcᵢ = 1/(2(n+λ))   i=1..2n
//  *
//  * 【UKF 流程伪代码】
//  *
//  * void UKF_Update(float x[], float P[][], float z_meas,
//  *                 void (*f)(), void (*h)(), ...)
//  * {
//  *     // ====== 1. 生成 Sigma 点 ======
//  *     float X[2*n+1][n];   // 2n+1 个 Sigma 点
//  *     Matrix_cholesky(P, L);  // Cholesky 分解：P = L*L^T
//  *     for (i = 0; i < 2*n+1; i++) {
//  *         X[i] = x + sqrt(n+λ) * (L的第i列 or -L的第i-n列);
//  *     }
//  *
//  *     // ====== 2. 预测：每个 Sigma 点穿过 f ======
//  *     float X_pred[2*n+1][n];
//  *     for (i = 0; i < 2*n+1; i++) {
