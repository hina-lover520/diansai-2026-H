//     float Q[2][2];    // 过程噪声协方差矩阵 (2x2)
//     float R[1][1];    // 测量噪声协方差矩阵 (1x1)（只测角度时）
//     float K[2];       // 卡尔曼增益 (2x1)
//     float dt;         // 采样周期（秒）
// } Kalman2D_t;

// /*===========================================================================
//  * 三、通用多维卡尔曼滤波器（矩阵版）
//  *===========================================================================
//  * 适用场景：状态维度 > 2，需要完整的矩阵运算。
//  *
//  * 通用模型：
//  *   状态方程：x(k) = F * x(k-1) + B * u(k) + w
//  *   观测方程：z(k) = H * x(k) + v
//  *
//  *   其中：
//  *     x  — 状态向量（你想估计的量）
//  *     F  — 状态转移矩阵（模型的核心：描述系统自身如何演化）
//  *     B  — 控制矩阵（控制输入如何影响状态）
//  *     u  — 控制向量（你主动施加的控制量，如 PWM 指令）
//  *     H  — 观测矩阵（传感器如何"看到"状态）
//  *     w  — 过程噪声 ~ N(0,Q)（模型误差）
//  *     v  — 测量噪声 ~ N(0,R)（传感器误差）
//  *
//  *   注意：本实现为轻量级，固定 n=2 或 n=3，不使用动态内存。
//  *===========================================================================*/

// /*===========================================================================
//  * 四、扩展卡尔曼滤波器（EKF）— 非线性系统的卡尔曼
//  *===========================================================================
//  * 传统 KF 要求模型是线性的（F 和 H 是常数矩阵）。
//  * 但实际系统往往是非线性的：
//  *
//  *   角度 = arctan(ay / az)                    ← 观测是非线性的
//  *   四元数传播 = 0.5 * q ⊗ ω                  ← 状态转移是非线性的
//  *   欧拉角动力学涉及 sin/cos                    ← 三角函数是非线性的
//  *
//  * EKF 的处理方式：
//  *   把非线性函数在当前估计点做一阶泰勒展开（求雅可比矩阵），
//  *   线性化后用标准 KF 公式。这是最常用的非线性格尔曼滤波。
//  *
//  * EKF 流程：
//  *   预测：x = f(x, u)              ← 用完整的非线性函数
//  *         P = F_jac * P * F_jac^T + Q  ← 用雅可比矩阵算协方差
//  *   更新：y = z - h(x)             ← 用非线性观测函数算残差
//  *         K = P * H_jac^T * (H_jac * P * H_jac^T + R)^-1
//  *         x = x + K * y
//  *         P = (I - K * H_jac) * P
//  *
//  *   其中 f() 和 h() 需要用户根据实际物理模型自行编写。
//  *===========================================================================*/

// /*===========================================================================
//  * 五、无迹卡尔曼滤波器（UKF）— 比 EKF 更准的非线性滤波
//  *===========================================================================
//  * EKF 用一阶泰勒近似，遇到强非线性（如四元数旋转）时误差较大。
//  * UKF 不线性化，而是用一组"Sigma 点"穿过整个非线性函数，
//  * 然后从变换后的点云中统计出均值和协方差。
//  *
//  * 优点：
//  *   - 不用求雅可比矩阵（省去推导，不易出错）
//  *   - 达到二阶泰勒精度（EKF 只有一阶）
//  *   - 对四元数、旋转矩阵等强非线性系统效果远好于 EKF
//  *
//  * 缺点：
//  *   - 计算量更大（n 维状态需 2n+1 个 Sigma 点）
//  *   - 嵌入式实现较重（浮点运算多）
//  *===========================================================================*/

// /*===========================================================================
//  * 附录：如何选择卡尔曼滤波变种？
//  *===========================================================================
//  *
//  *   场景                                  推荐
//  *   ──────────────────────────────────────────────────
//  *   只估计一个角度，有陀螺仪              1D KF + 角速度模型
//  *   估计角度 + 补偿陀螺仪零偏              2D KF
//  *   加速度计/磁力计非线性观测角度          EKF
//  *   四元数姿态估计                         UKF（或 EKF）
//  *   GPS + IMU 组合导航（强非线性）         UKF 或粒子滤波
//  *   线性系统、计算资源极度受限             标准 KF
//  *   单片机应用、需要快速落地               1D/2D 标准 KF
//  *
//  *===========================================================================*/

