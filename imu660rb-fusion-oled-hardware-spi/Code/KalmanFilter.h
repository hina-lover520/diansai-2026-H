// /*===========================================================================
//  * 卡尔曼滤波 — 头文件
//  *===========================================================================
//  *
//  * 【什么是卡尔曼滤波的"模型"？】
//  *
//  * 卡尔曼滤波的核心是两样东西：
//  *
//  *   1. 状态转移模型（运动/物理模型）
//  *      "假如没有测量值，系统自己会怎么变？"
//  *      比如：角度 = 上一时刻角度 + 角速度 × dt
//  *      这是你根据物理规律对系统做出的预测。
//  *
//  *   2. 观测模型（传感器模型）
//  *      "传感器测到的值和我关心的状态是什么关系？"
//  *      比如：IMU 直接输出角度 → 观测值 = 1.0 × 真实角度 + 噪声
//  *      这是你描述传感器如何"看到"系统状态的模型。
//  *
//  * 卡尔曼滤波就是在这两者之间做加权平均：
//  *   - 模型预测告诉你"大概在哪"
//  *   - 传感器测量告诉你"看到在哪"
//  *   - 卡尔曼增益决定更信谁（谁噪声小就信谁多）
//  *
//  *===========================================================================*/

// /*===========================================================================
//  * 一、一维卡尔曼滤波器（标量版）—— 最轻量、最实用
//  *===========================================================================
//  * 适用场景：只估计一个量（如角度），计算量极小，适合单片机。
//  *
//  * 模型（状态转移）：
//  *   x(k) = x(k-1) + 角速度*dt   （恒定角速度模型）
//  *   或 x(k) = x(k-1)            （恒定值模型，没有陀螺仪时使用）
//  *
//  * 模型（观测）：
//  *   z(k) = x(k)                  （传感器直接测角度）
//  *
//  * 状态变量说明：
//  *   x  = 估计值（滤波后的角度）
//  *   P  = 估计误差协方差（对当前估计有多不确定）
//  *   Q  = 过程噪声协方差（模型有多不准，越大越信传感器）
//  *   R  = 测量噪声协方差（传感器有多不准，越大越信模型）
//  *   K  = 卡尔曼增益（自动计算，决定信模型还是信传感器）
//  *===========================================================================*/
// typedef struct {
//     float x;     // 状态估计值（滤波输出）
//     float P;     // 估计误差协方差
//     float Q;     // 过程噪声协方差（模型噪声）
//     float R;     // 测量噪声协方差（传感器噪声）
//     float K;     // 卡尔曼增益（自动更新）
//     float dt;    // 采样周期（秒）
// } Kalman1D_t;

// /*===========================================================================
//  * 二、二维卡尔曼滤波器 —— 角度 + 角速度
//  *===========================================================================
//  * 适用场景：同时估计角度和角速度（陀螺仪偏置补偿）。
//  *
//  * 状态向量：x = [角度, 角速度]^T
//  *
//  * 状态转移模型（恒定角速度）：
//  *   角度(k+1) = 角度(k) + 角速度(k) * dt
//  *   角速度(k+1) = 角速度(k)
//  *
//  *   F = [1,  dt]
//  *       [0,   1]
//  *
//  * 观测模型：
//  *   传感器只测角度 → H = [1, 0]
//  *   传感器测角度+角速度 → H = [[1,0],[0,1]]
//  *
//  * 这是你 IMU660RB + 舵机场景最推荐使用的版本！
//  *===========================================================================*/
